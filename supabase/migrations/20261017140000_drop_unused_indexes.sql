-- Careful filtering (why only 78 of 602 zero-scan indexes are dropped):
--   • idx_scan = 0 over the DB's full stats lifetime (stats_reset IS NULL; other
--     indexes show up to 2.4M scans, so the counters are real) — never used;
--   • NOT unique / primary-key / constraint-backing (those enforce integrity);
--   • NOT covering a foreign key — 170 of the zero-scan "safe" indexes are the
--     sole cover for an FK (ordered-prefix match on the FK columns); dropping
--     those would re-create "unindexed foreign key" warnings and slow cascade
--     deletes / joins, so they are KEPT.
-- Net effect: less write amplification on these tables; no read-path risk (an
-- unused index never helped a read). Fully reversible — each index's original
-- CREATE is recorded at the bottom; re-run one to restore it if a future query
-- path needs it.

